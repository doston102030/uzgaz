export function revenueByDay(days = 14) {
  const out: { date: string; revenue: number; orders: number }[] = [];
  const base = new Date("2025-09-12");
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(base);
    d.setDate(d.getDate() - i);
    const seed = d.getDate() + d.getMonth() * 3;
    const revenue = 1_800_000 + ((seed * 137) % 1_600_000);
    const ordersCount = 8 + ((seed * 7) % 20);
    const pad = (n: number) => (n < 10 ? `0${n}` : String(n));
    out.push({
      date: `${pad(d.getDate())}.${pad(d.getMonth() + 1)}`,
      revenue,
      orders: ordersCount,
    });
  }
  return out;
}
